def parse_prices(raw):
    data = []
    for line in raw.strip().split('\n'):
        parts = line.split(',')
        ts = int(parts[0])
        price = float(parts[1])
        data.append((ts, price))
    return data


def trading_days_until(dt, deadline):
    """Count trading days (weekdays) from dt to deadline inclusive."""
    days = 0
    current = dt.date()
    end = deadline.date()
    while current <= end:
        if current.weekday() < 5:
            days += 1
        current += timedelta(days=1)
    return days


